fun stringsFor(lang: Lang) = if (lang == Lang.VI) Vietnamese else English

/** Ngôn ngữ đã chọn; chưa chọn thì theo ngôn ngữ máy (tiếng Việt nếu máy để tiếng Việt). */
fun currentLang(context: Context): Lang =
    Prefs.language(context) ?: if (Locale.getDefault().language == "vi") Lang.VI else Lang.EN

fun strings(context: Context) = stringsFor(currentLang(context))

